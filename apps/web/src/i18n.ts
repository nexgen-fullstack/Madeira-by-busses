const DICTS: Record<Lang, Dict> = { uk, pt, en };
const LOCALES: Record<Lang, string> = { uk: 'uk-UA', pt: 'pt-PT', en: 'en-GB' };

export function detectLang(): Lang {
  const langs =
    typeof navigator === 'undefined' ? [] : (navigator.languages ?? [navigator.language]);
  for (const l of langs) {
    const code = l.slice(0, 2).toLowerCase();
    if (code === 'uk' || code === 'pt' || code === 'en') return code;
  }
  return 'en';
}

export interface I18n {
  lang: Lang;
  locale: string;
  t: (key: Key, params?: Record<string, string | number>) => string;
  /** Plural-aware: picks the form for `params.n`. */
  tn: (key: Key, n: number, params?: Record<string, string | number>) => string;
}

export function makeI18n(lang: Lang): I18n {
  const dict = DICTS[lang];
  const plural = new Intl.PluralRules(LOCALES[lang]);
  const fill = (s: string, params: Record<string, string | number> = {}) =>
    s.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? `{${k}}`));
  return {
    lang,
    locale: LOCALES[lang],
    t: (key, params) => {
      const e = dict[key] ?? uk[key];
      return fill(typeof e === 'string' ? e : e.other, params);
    },
    tn: (key, n, params) => {
      const e = dict[key] ?? uk[key];
      const form = typeof e === 'string' ? e : (e[plural.select(n)] ?? e.other);
      return fill(form, { n, ...params });
    },
  };
}

